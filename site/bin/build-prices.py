#!/usr/bin/env python3
"""Turn the price list people edit into the one the site-worker charges from.

Writes src/prices.js in a site-worker checkout (FC-Public-Media/site-worker) beside this repository,
or at FCPM_SITE_WORKER, from site/_data/membership.yml and classes.yml; --check fails on drift.
"TODO" prices are left out. See docs/payments.md#prices.
"""

import argparse
import json
import os
import pathlib
import sys

import yaml

# SITE is the Jekyll source (site/); REPO is the repository root.
SITE = pathlib.Path(__file__).resolve().parent.parent
REPO = SITE.parent
WORKER = pathlib.Path(os.environ.get("FCPM_SITE_WORKER") or REPO.parent / "site-worker")
OUT = WORKER / "src" / "prices.js"

BANNER = """\
// The price list the broker charges from.
//
// GENERATED by fcpublicmedia.org's site/bin/build-prices.py from its
// site/_data/membership.yml and classes.yml. Do not edit this file — edit those,
// run the script with this checkout beside it, and commit both repositories.
//
// Amounts are in cents, because that is what Stripe takes and because money
// in floating point eventually charges somebody $69.99999.
//
// Changing a price here is a commit, which is the point: `git log -p` on the
// data files is the price history, and a pull request is the announcement.

export default """

# Stripe takes the smallest unit; everything below is integer cents.
CENTS = 100


def load(name):
    with open(SITE / "_data" / name, encoding="utf-8") as handle:
        return yaml.safe_load(handle)


def amount(value):
    """Cents for a positive int or float in whole cents; None for anything else."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    if value <= 0:
        return None
    cents = round(value * CENTS)
    # Not a whole cent: not a price.
    if abs(value * CENTS - cents) > 0.001:
        return None
    return int(cents)


def slug(name):
    return "".join(character.lower() if character.isalnum() else "-" for character in name).strip("-")


def build():
    """The catalog, plus the reasons anything was left out of it."""
    items = {}
    skipped = []

    membership = load("membership.yml")

    for tier in membership.get("tiers") or []:
        cents = amount(tier.get("price"))
        sku = f"membership:{slug(tier['name'])}"
        if cents is None:
            skipped.append(f"{sku} — price is {tier.get('price')!r}")
            continue
        items[sku] = {
            "kind": "membership",
            "name": f"{tier['name']} membership",
            # Shown on the Stripe page; `renews` only when the buyer chose the yearly subscription.
            "description": "One year from today.",
            "renews": "Renews on the day you joined, not in January.",
            "amount": cents,
            # The buyer chooses one payment or a yearly subscription, same amount.
            "interval": "year",
        }

    # Drop-in attendance at one session, not course registration.
    classes = load("classes.yml")
    dropin = classes.get("dropin") or {}
    for who in ("public", "member"):
        cents = amount(dropin.get(who))
        sku = f"class-dropin:{who}"
        if cents is None:
            skipped.append(f"{sku} — price is {dropin.get(who)!r}")
            continue
        items[sku] = {
            "kind": "class",
            "name": f"Class drop-in ({who})",
            "description": "Attendance at one class session.",
            "amount": cents,
            "interval": None,
        }

    return {"currency": "usd", "items": items}, skipped


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed file has drifted from the data files",
    )
    args = parser.parse_args()

    catalog, skipped = build()
    rendered = BANNER + json.dumps(catalog, indent=2, sort_keys=True) + ";\n"

    if not (WORKER / "wrangler.jsonc").exists():
        print(f"No site-worker checkout at {WORKER}: clone FC-Public-Media/site-worker beside this "
              "repository, or set FCPM_SITE_WORKER.", file=sys.stderr)
        return 0 if args.check else 2

    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != rendered:
            print(
                f"{OUT} is out of date.\n"
                "A price changed in site/_data/ without the site-worker's copy being "
                "rebuilt. Run:\n\n    python3 site/bin/build-prices.py\n\n"
                "and commit the result in both repositories.",
                file=sys.stderr,
            )
            return 1
        print(f"{OUT} matches the data files.")
    else:
        OUT.write_text(rendered, encoding="utf-8")
        print(f"Wrote {OUT} — {len(catalog['items'])} for sale.")

    for note in skipped:
        print(f"  not for sale: {note}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
